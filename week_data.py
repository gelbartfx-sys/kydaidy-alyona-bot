def self_check() -> None:
    """Сторожа канона: структура, отсутствие повторов с бесплатными вечерами и
    запрет на обещание общего банка (вечера — личный шаг)."""
    from sixsec_data import SIXSEC as FREE_EVENINGS  # бесплатные три

    for opora, days in WEEK_EVENINGS.items():
        assert len(days) == 7, f"{opora}: вечеров {len(days)}, витрина обещает 7"
        assert [d["den"] for d in days] == list(range(1, 8)), f"{opora}: дни идут не по порядку"
        for d in days:
            for field in ("zadanie", "vozvrat_vopros", "otvet_da", "otvet_net"):
                assert d[field].strip(), f"{opora} день {d['den']}: пустое поле {field}"
            # Вечер — личный шаг. Общий банк растёт только на парном чек-ине.
            for forbidden in ("в банк", "общий счёт", "общий банк"):
                assert forbidden not in d["otvet_da"].lower(), \
                    f"{opora} день {d['den']}: вечер снова обещает общий банк"

    assert set(WEEK_EVENINGS) == set(WEEK_INTRO), "опоры вечеров и вступлений разошлись"

    # Ни одного повтора платного вечера с бесплатным: человек, прошедший
    # дегустацию, не должен купить за 99 ₽ то же самое.
    for opora, days in WEEK_EVENINGS.items():
        free = {e["zadanie"].strip().lower() for e in FREE_EVENINGS.get(opora, [])}
        for d in days:
            assert d["zadanie"].strip().lower() not in free, \
                f"{opora} день {d['den']}: задание дублирует бесплатный вечер"

    assert len(WEEK_SREZ["questions"]) == 4, "срез должен покрывать все четыре опоры"
    assert {q["opora"] for q in WEEK_SREZ["questions"]} == set(WEEK_EVENINGS), \
        "опоры среза не совпадают с опорами вечеров"


